# Blok IF yang akan berjalan (karena alien berwarna 'green')
alien_color = 'green'

if alien_color == 'green':
    print("Kamu menembak alien hijau, kamu baru saja mendapat 5 poin!")
else:
    print("Kamu baru saja mendapat 10 poin!")


# Blok ELSE yang akan berjalan (karena alien berwarna selain 'green')
alien_color = 'yellow'

if alien_color == 'green':
    print("Kamu menembak alien hijau, kamu baru saja mendapat 5 poin!")
else:
    print("Kamu baru saja mendapat 10 poin!")