age = 100  # Bisa ubah angka ini untuk menguji kondisi lain

if age < 2:
    print("Orang ini adalah seorang bayi (baby).")
elif age < 4:
    print("Orang ini adalah seorang balita (toddler).")
elif age < 13:
    print("Orang ini adalah seorang anak-anak (kid).")
elif age < 20:
    print("Orang ini adalah seorang remaja (teenager).")
elif age < 65:
    print("Orang ini adalah seorang dewasa (adult).")
else:
    print("Orang ini adalah seorang lansia (elder).")